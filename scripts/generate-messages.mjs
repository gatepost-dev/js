// Writes packages/field/src/spec-messages.ts from the English message catalogue of the field.
// Run `pnpm generate` after the spec submodule changes. `pnpm generate:check` fails when the
// file is out of date.
import { readFileSync, writeFileSync } from 'node:fs';
import process from 'node:process';
import { URL } from 'node:url';

const root = new URL('../', import.meta.url);
const source = new URL('spec/messages/field_en.arb', root);
const target = new URL('packages/field/src/spec-messages.ts', root);
const KEY = /^[a-z][a-z_]*$/;

// These lines are the SPDX tags of the generated file. REUSE must not read them as tags of this
// script, where they end in a quote and a comma.
// REUSE-IgnoreStart
const HEADER = [
  '// SPDX-FileCopyrightText: 2026 The Gatepost authors',
  '// SPDX-License-Identifier: Apache-2.0',
  '// @generated by scripts/generate-messages.mjs from spec/messages. Do not edit this file.',
  '',
];
// REUSE-IgnoreEnd

// A single-quoted literal in printable ASCII (TELL-14). Each other UTF-16 unit becomes an escape,
// so a translation can use any script.
function quoted(text) {
  const escaped = text
    .replace(/[\\']/g, (character) => `\\${character}`)
    .replace(/[^ -~]/g, (unit) => `\\u${unit.charCodeAt(0).toString(16).padStart(4, '0')}`);
  return `'${escaped}'`;
}

// The keys become property names and a union type, so each one must be a plain name. ARB keeps
// the description of a key under "@key", and the locale under "@@locale".
function readMessages() {
  const catalogue = JSON.parse(readFileSync(source, 'utf8'));
  const keys = Object.keys(catalogue).filter((key) => !key.startsWith('@'));
  for (const key of keys) {
    if (!KEY.test(key)) {
      throw new Error(`The key ${JSON.stringify(key)} is not lower case with underscores.`);
    }
    if (typeof catalogue[key] !== 'string') {
      throw new Error(`The message ${JSON.stringify(key)} is not text.`);
    }
  }
  if (keys.length === 0) {
    throw new Error('The catalogue has no message.');
  }
  return keys.map((key) => [key, catalogue[key]]);
}

function render(messages) {
  return [
    ...HEADER,
    '/**',
    ' * The key of each message that the field shows. `spec/field.md` says when each one shows.',
    ' */',
    'export type MessageKey =',
    ...messages.map(
      ([key], index) => `  | ${quoted(key)}${index === messages.length - 1 ? ';' : ''}`,
    ),
    '',
    '/**',
    ' * The text of the field in one language, one message for each key. A name in braces, such',
    ' * as `{count}`, is a placeholder that the field fills in.',
    ' */',
    'export type Messages = Readonly<Record<MessageKey, string>>;',
    '',
    '/**',
    ' * The British English messages of the spec.',
    ' *',
    ' * @internal',
    ' */',
    'export const ENGLISH: Messages = {',
    ...messages.map(([key, text]) => `  ${key}: ${quoted(text)},`),
    '};',
    '',
  ].join('\n');
}

const args = process.argv.slice(2);
const unknown = args.find((argument) => argument !== '--check');
if (unknown !== undefined) {
  process.stderr.write(`Unknown argument ${unknown}. Use --check or no argument.\n`);
  process.exit(2);
}

// A reader of this output wants the problem, not a stack trace.
function readCurrent() {
  try {
    return readFileSync(target, 'utf8');
  } catch {
    return null;
  }
}

let text;
try {
  text = render(readMessages());
} catch (error) {
  process.stderr.write(`${error instanceof Error ? error.message : String(error)}\n`);
  process.exit(1);
}
if (args.includes('--check')) {
  if (readCurrent() !== text) {
    process.stderr.write(
      'packages/field/src/spec-messages.ts is out of date. Run pnpm generate.\n',
    );
    process.exit(1);
  }
} else {
  writeFileSync(target, text);
}

// Writes packages/core/src/spec-data.ts from the JSON files in spec/data.
// Run `pnpm generate` after the spec submodule changes. `pnpm generate:check` fails
// when the file is out of date.
import { readFileSync, writeFileSync } from 'node:fs';
import process from 'node:process';
import { URL } from 'node:url';

const root = new URL('../', import.meta.url);
const target = new URL('packages/core/src/spec-data.ts', root);

function readJson(path) {
  return JSON.parse(readFileSync(new URL(path, root), 'utf8'));
}

// A label such as "U+2013" becomes the regular-expression escape for that code point.
function escapeCodePoint(label) {
  return '\\u' + label.slice(2);
}

function doc(summary) {
  return ['/**', ` * ${summary}`, ' *', ' * @internal', ' */'];
}

function quoted(text) {
  return `'${text}'`;
}

function render() {
  const { states } = readJson('spec/data/states.json');
  const precision = readJson('spec/data/precision.json');
  const format = readJson('spec/data/format.json');
  let start = 0;
  const bounds = format.segments.map((segment) => {
    const line = `  ${segment.name}: { start: ${start}, end: ${start + segment.length} },`;
    start += segment.length;
    return line;
  });
  const rules = format.segments.map((segment) =>
    [
      `  { name: ${quoted(segment.name)}, length: ${segment.length},`,
      ` characters: ${quoted(segment.characters)}, minimum: ${segment.minimum ?? 'null'} },`,
    ].join(''),
  );
  const order = format.segments.map((segment) => quoted(segment.name)).join(', ');
  const separators = format.separators.map(escapeCodePoint).join('');
  const fixes = (table) =>
    Object.entries(table).map(([from, to]) => `  [${quoted(from)}, ${quoted(to)}],`);
  return [
    '// SPDX-FileCopyrightText: 2026 The Gatepost authors',
    '// SPDX-License-Identifier: Apache-2.0',
    '// @generated by scripts/generate-spec-data.mjs from spec/data. Do not edit this file.',
    '',
    "import type { Precision, PrecisionThreshold, SegmentBounds, SegmentRule } from './types.js';",
    '',
    ...doc('State codes and names, from spec/data/states.json.'),
    'export const STATES: ReadonlyMap<string, string> = new Map([',
    ...states.map((state) => `  [${quoted(state.code)}, ${quoted(state.name)}],`),
    ']);',
    '',
    ...doc('Segment names from the least to the most precise.'),
    `export const PRECISION_ORDER: readonly Precision[] = [${order}];`,
    '',
    ...doc('The rule for each segment, in order.'),
    'export const SEGMENT_RULES: readonly SegmentRule[] = [',
    ...rules,
    '];',
    '',
    ...doc('Where each segment starts and ends in a compact code.'),
    'export const SEGMENT_BOUNDS: Readonly<Record<Precision, SegmentBounds>> = {',
    ...bounds,
    '};',
    '',
    ...doc('GPS accuracy limits, from spec/data/precision.json.'),
    'export const PRECISION_THRESHOLDS: readonly PrecisionThreshold[] = [',
    ...precision.thresholds.map(
      (row) => `  { maxAccuracyM: ${row.maxAccuracyM}, precision: ${quoted(row.precision)} },`,
    ),
    '];',
    '',
    ...doc('The precision for an accuracy above every limit.'),
    `export const PRECISION_FALLBACK: Precision = ${quoted(precision.fallback)};`,
    '',
    ...doc('Characters that normalize removes. Use it only with replace, because of flag g.'),
    `export const SEPARATORS: RegExp = /[${separators}]/gu;`,
    '',
    ...doc('Old 6-digit NIPOST postcodes.'),
    `export const LEGACY: RegExp = /${format.legacyPattern}/u;`,
    '',
    ...doc('Typo fixes in digit segments.'),
    'export const DIGIT_FIXES: ReadonlyMap<string, string> = new Map([',
    ...fixes(format.suggestions.digits),
    ']);',
    '',
    ...doc('Typo fixes in letter segments.'),
    'export const LETTER_FIXES: ReadonlyMap<string, string> = new Map([',
    ...fixes(format.suggestions.letters),
    ']);',
    '',
  ].join('\n');
}

const text = render();
if (process.argv.includes('--check')) {
  if (readFileSync(target, 'utf8') !== text) {
    process.stderr.write('packages/core/src/spec-data.ts is out of date. Run pnpm generate.\n');
    process.exit(1);
  }
} else {
  writeFileSync(target, text);
}

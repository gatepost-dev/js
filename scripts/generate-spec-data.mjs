// Writes packages/core/src/spec-data.ts from the JSON files in spec/data.
// Run `pnpm generate` after the spec submodule changes. `pnpm generate:check` fails
// when the file is out of date.
import { readFileSync, writeFileSync } from 'node:fs';
import process from 'node:process';
import { URL } from 'node:url';

const DATA_VERSION = 1;
const SEPARATOR_LABEL = /^U\+[0-9A-F]{4,6}$/;

const root = new URL('../', import.meta.url);
const target = new URL('packages/core/src/spec-data.ts', root);

// These lines are the SPDX tags of the generated file. REUSE must not read them as tags of this
// script, where they end in a quote and a comma.
// REUSE-IgnoreStart
const HEADER = [
  '// SPDX-FileCopyrightText: 2026 The Gatepost authors',
  '// SPDX-License-Identifier: Apache-2.0',
  '// @generated by scripts/generate-spec-data.mjs from spec/data. Do not edit this file.',
  '',
  "import type { Precision, PrecisionThreshold, SegmentBounds, SegmentRule } from './types.js';",
  '',
];
// REUSE-IgnoreEnd

function readJson(path) {
  const dataFile = JSON.parse(readFileSync(new URL(path, root), 'utf8'));
  if (dataFile.version !== DATA_VERSION) {
    throw new Error(`${path} has version ${dataFile.version}, not ${DATA_VERSION}.`);
  }
  return dataFile;
}

// The braced form holds any code point. The four-digit form stops at U+FFFF, and a regular
// expression reads a longer label as four digits followed by plain characters.
function bracedEscape(hex) {
  return '\\u{' + hex + '}';
}

// A label such as "U+2013" becomes the escape for that code point. A label of another
// shape would give a wrong regular expression and no error, so it throws.
function escapeCodePoint(label) {
  if (!SEPARATOR_LABEL.test(label)) {
    throw new Error(`Bad separator label "${label}". Write U+ and 4 to 6 upper-case hex digits.`);
  }
  return bracedEscape(label.slice(2));
}

function escapeCharacter(character) {
  if (character === '\\' || character === "'") {
    return '\\' + character;
  }
  return bracedEscape(character.codePointAt(0).toString(16).toUpperCase().padStart(4, '0'));
}

// Printable ASCII only, so a name with a quote, a backslash or a non-ASCII letter still
// compiles, keeps its text and passes TELL-14.
function quoted(text) {
  return `'${text.replace(/[\\']|[^ -~]/gu, escapeCharacter)}'`;
}

function doc(summary) {
  return ['/**', ` * ${summary}`, ' *', ' * @internal', ' */'];
}

function renderStates(states) {
  return [
    ...doc('State codes and names, from spec/data/states.json.'),
    'export const STATES: ReadonlyMap<string, string> = new Map([',
    ...states.map((state) => `  [${quoted(state.code)}, ${quoted(state.name)}],`),
    ']);',
  ];
}

function renderPrecisionOrder(format) {
  const order = format.segments.map((segment) => quoted(segment.name)).join(', ');
  return [
    ...doc('Segment names from the least to the most precise.'),
    `export const PRECISION_ORDER: readonly Precision[] = [${order}];`,
  ];
}

function renderSegmentRules(format) {
  const rules = format.segments.map((segment) =>
    [
      `  { name: ${quoted(segment.name)}, length: ${segment.length},`,
      ` characters: ${quoted(segment.characters)}, minimum: ${segment.minimum ?? 'null'} },`,
    ].join(''),
  );
  return [
    ...doc('The rule for each segment, in order.'),
    'export const SEGMENT_RULES: readonly SegmentRule[] = [',
    ...rules,
    '];',
  ];
}

function renderSegmentBounds(format) {
  let start = 0;
  const bounds = format.segments.map((segment) => {
    const line = `  ${segment.name}: { start: ${start}, end: ${start + segment.length} },`;
    start += segment.length;
    return line;
  });
  return [
    ...doc('Where each segment starts and ends in a compact code.'),
    'export const SEGMENT_BOUNDS: Readonly<Record<Precision, SegmentBounds>> = {',
    ...bounds,
    '};',
  ];
}

function renderPrecisionThresholds(precision) {
  return [
    ...doc('GPS accuracy limits, from spec/data/precision.json.'),
    'export const PRECISION_THRESHOLDS: readonly PrecisionThreshold[] = [',
    ...precision.thresholds.map(
      (row) => `  { maxAccuracyM: ${row.maxAccuracyM}, precision: ${quoted(row.precision)} },`,
    ),
    '];',
  ];
}

function renderPrecisionFallback(precision) {
  return [
    ...doc('The precision for an accuracy above every limit.'),
    `export const PRECISION_FALLBACK: Precision = ${quoted(precision.fallback)};`,
  ];
}

function renderMaxInputCodePoints(format) {
  return [
    ...doc('The most code points that parse reads. Longer input fails before normalize runs.'),
    `export const MAX_INPUT_CODE_POINTS: number = ${format.maxInputCodePoints};`,
  ];
}

function renderSeparators(format) {
  const separators = format.separators.map(escapeCodePoint).join('');
  return [
    ...doc('Characters that normalize removes. Use it only with replace, because of flag g.'),
    `export const SEPARATORS: RegExp = /[${separators}]/gu;`,
  ];
}

function renderLegacy(format) {
  return [
    ...doc('Old 6-digit NIPOST postcodes.'),
    `export const LEGACY: RegExp = /${format.legacyPattern}/u;`,
  ];
}

function fixEntries(table) {
  return Object.entries(table).map(([from, to]) => `  [${quoted(from)}, ${quoted(to)}],`);
}

function renderDigitFixes(format) {
  return [
    ...doc('Typo fixes in digit segments.'),
    'export const DIGIT_FIXES: ReadonlyMap<string, string> = new Map([',
    ...fixEntries(format.suggestions.digits),
    ']);',
  ];
}

function renderLetterFixes(format) {
  return [
    ...doc('Typo fixes in letter segments.'),
    'export const LETTER_FIXES: ReadonlyMap<string, string> = new Map([',
    ...fixEntries(format.suggestions.letters),
    ']);',
  ];
}

function render() {
  const { states } = readJson('spec/data/states.json');
  const precision = readJson('spec/data/precision.json');
  const format = readJson('spec/data/format.json');
  const blocks = [
    renderStates(states),
    renderPrecisionOrder(format),
    renderSegmentRules(format),
    renderSegmentBounds(format),
    renderPrecisionThresholds(precision),
    renderPrecisionFallback(precision),
    renderMaxInputCodePoints(format),
    renderSeparators(format),
    renderLegacy(format),
    renderDigitFixes(format),
    renderLetterFixes(format),
  ];
  return [...HEADER, ...blocks.flatMap((block) => [...block, ''])].join('\n');
}

const args = process.argv.slice(2);
const unknown = args.find((argument) => argument !== '--check');
if (unknown !== undefined) {
  process.stderr.write(`Unknown argument ${unknown}. Use --check or no argument.\n`);
  process.exit(2);
}

const text = render();
if (args.includes('--check')) {
  if (readFileSync(target, 'utf8') !== text) {
    process.stderr.write('packages/core/src/spec-data.ts is out of date. Run pnpm generate.\n');
    process.exit(1);
  }
} else {
  writeFileSync(target, text);
}
